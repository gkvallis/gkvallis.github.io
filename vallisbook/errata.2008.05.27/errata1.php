reader to work a little. These are collected at the head of the list, and are followed by the typos
in page order. Unless stated, none of the corrections affect the subsequent arguments or
derivations in the book. If you find other errors, or if you think something is poorly explained,
please contact the author at &#8216;gkv-at-princeton-dot-edu&#8217;.
