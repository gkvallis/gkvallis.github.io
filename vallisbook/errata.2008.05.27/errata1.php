<!--l. 50--><p class="indent" >   The following errata and comments apply to the <span 
class="ecti-1000">first printing </span>of the book. Most of the
errors have been corrected in the second printing, although a few remain. If you
have the second printing of the book, available from October 2007, please see the
corresponding errata sheet. (The second printing has &#8216;Reprinted 2007&#8217; on the copyright
page.) Errors that occur in both printings are (or should be) listed in both errata
sheets.
<!--l. 52--><p class="indent" >   Most of the errors should not, I think, cause too much frustration to either the careful
