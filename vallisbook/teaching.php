<h1>Teaching and Learning with the Book</h1>

<h2>Teaching with the Book</h2>

<p>The book is divided into four parts, each roughly corresponding to a one term course. In fact the book grew out of such courses, taught by the author and his colleagues over the years at Princeton and elsewhere. These parts are:</p>

<p>
<table>
<tr><td>I</td><td>Fundamentals of Geophysical Fluid Dynamics</td></tr>
<tr><td>II</td><td>Waves, Instabilities and Turbulence</td></tr>
<tr><td>III</td><td>Large-Scale Atmospheric Circulation</td></tr>
<tr><td>IV</td><td>Large-Scale Oceanic Circulation</td></tr>
</table>
</p>

<p>Note though that each section within the book does <i>not</i> correspond to one lecture or similar; the sections are logical units, not temporal units, and may differ considerably in length.</p>

<p>The last two parts, as well as aspects of Part II, aim to take the reader gently to the frontiers of current thinking, and the instructor may wish to supplement the book with other material such as review articles and papers.  Parts III and IV would normally be taught after a course in basic GFD (i.e., after Part I), but do not require much of the material of Part II. When I was at Princeton, a basic GFD course was usually taught in the first semester, and a dynamical oceanography course is generally taught in the semester following, coincident with a second semester of GFD. Some instructors will likely wish to mix and match from among the different parts, and this too should be possible with a little effort: one could envision a dynamical meteorology and atmospheric general circulation course that combined material from Parts I and III.</p>

<h2>Learning from the Book</h2>

<p>If you are reading the book by yourself the default is just to read the chapters in order, from start to finish. However, some readers will have a background in one topic, but not in another. For example, if you may already know about GFD and want to learn about the atmospheric or oceanic general circulation, then start reading at the beginning of Parts III or IV, referring back as needed. The chapters are, within reason, self-contained and there is some repetition of material to make this possible without undue pain. It is certainly possible to go from Part I to Parts III and IV, referring back to Part II as needed.</p>

<p>Finally, note also that all the figures from the book are available for download as PDF files --- click on 'Figures' on the left panel.</p>

