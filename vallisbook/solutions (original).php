<h1>Solutions</h1>

<p>All solutions below are password-protected. If you are an instructor using the book in a course you may request access information from the author <?include("http://www.vallisbook.org/layout/em_gkv_name.php")?> (<a href="solutions/solution_contributors.php">list of people with access</a>).</p>

<p>Only a few solutions are currently posted, but we expect to post more soon. You can help this process by contributing your own solutions and encouraging others to post theirs. These can be solutions to problems not yet solved below or alternative solutions complementing or clarifying existing solutions. Instructors might want to encourage their students to submit any of their good solutions. New problems that are not in the book and, if possible, their solutions are also welcome. To maintain a uniform standard of  presentations, solutions may be written using the latex template <a href="sol-template.tex">sol-template.tex</a> (see <a href="sol-template.pdf">template as PDF</a>). Solutions (as tex and pdf files) should be sent to the author <?include("http://www.vallisbook.org/layout/em_gkv_name.php")?>. Thank you very much for your contributions.

<p>The solutions are provided for your benefit, but are not guaranteed accurate.</p>

